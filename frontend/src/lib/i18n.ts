/** `{{count}}` мэтийн орлуулга бүхий утгууд. */
export type TranslateVars = Record<string, string | number>;

function interpolate(template: string, vars: TranslateVars): string {
  return template.replace(/\{\{\s*(\w+)\s*\}\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

/**
 * Хоёр хэлбэрээр дуудаж болно:
 *   translate(locale, key, "fallback")
 *   translate(locale, key, { count: 3 })
 *   translate(locale, key, "fallback", { count: 3 })
 */
export function translate(
  locale: Locale,
  key: string,
  fallbackOrVars?: string | TranslateVars,
  maybeVars?: TranslateVars
): string {
  const hasFallback = typeof fallbackOrVars === "string";
  const fallback = hasFallback ? fallbackOrVars : undefined;
  const vars = hasFallback ? maybeVars : fallbackOrVars;

  const entry = dict[key];
  const template = entry ? entry[locale] ?? entry.mn ?? key : fallback ?? key;
  return vars ? interpolate(template, vars) : template;
}

export function pickLocalized(value: { mn?: string; en?: string } | undefined | null, locale: Locale): string {
  if (!value) return "";
  return value[locale] || value.mn || value.en || "";
}
